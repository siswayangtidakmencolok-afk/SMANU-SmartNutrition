const _byId = new Map<string, FoodNutrition>(
  FOOD_DATABASE.map((f) => [f.foodId, f])
);

/** Look up a food item by its stable foodId slug. */
export function getFoodById(foodId: string): FoodNutrition | undefined {
  return _byId.get(foodId);
}

/**
 * Simple fuzzy search — returns items where namePrimary or any alias
 * contains the query string (case-insensitive).
 */
export function searchFoodByName(query: string): FoodNutrition[] {
  const q = query.toLowerCase().trim();
  if (!q) return [];
  return FOOD_DATABASE.filter(
    (f) =>
      f.namePrimary.toLowerCase().includes(q) ||
      f.nameAliases.some((a) => a.toLowerCase().includes(q)) ||
      (f.nameEnglish?.toLowerCase().includes(q) ?? false)
  );
}

/**
 * Compute estimated nutrition for a given food and portion weight.
 * Returns null if the food or the energy value is not available.
 */
export function estimateNutrition(
  foodId: string,
  portionG: number
): {
  energyKcal: number;
  proteinG: number;
  fatG: number;
  carbG: number;
  fiberG?: number;
  portionG: number;
  scaleFactor: number;
  isEstimate: boolean;
  dataSource: string;
  assumptions: string;
} | null {
  const food = getFoodById(foodId);
  if (!food || food.energyKcal == null) return null;

  const scale = portionG / 100;

  const assumptions: string[] = [
    `Nilai per 100 g dari ${food.dataSource}.`,
    `Porsi diasumsikan ${portionG} g — bukan hasil timbangan langsung.`,
  ];
  if (food.isEstimate) {
    assumptions.push(`Catatan: ${food.estimateNote ?? "Nilai merupakan estimasi."}`);
  }

  return {
    energyKcal: Math.round(food.energyKcal * scale),
    proteinG: Math.round(food.proteinG * scale * 10) / 10,
    fatG: Math.round(food.fatG * scale * 10) / 10,
    carbG: Math.round(food.carbG * scale * 10) / 10,
    fiberG: food.fiberG != null ? Math.round(food.fiberG * scale * 10) / 10 : undefined,
    portionG,
    scaleFactor: scale,
    isEstimate: food.isEstimate,
    dataSource: food.dataSource,
    assumptions: assumptions.join(" "),
  };
}
